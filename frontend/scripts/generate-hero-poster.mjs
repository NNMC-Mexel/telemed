/**
 * Builds the responsive hero poster set from the master still frame.
 *
 * The hero paints this image before the campus video is allowed to download,
 * so it sits on the critical path — it has to be small enough to arrive in the
 * first round trips. Two things make that cheap here: the hero blurs the media
 * by ~2px and lays a near-opaque scrim over it, so detail beyond ~1280px is
 * thrown away on screen anyway.
 *
 * Outputs:
 *   public/nnmc-campus-hero-poster-{828,1280,1600}.{avif,webp,jpg}
 *   src/assets/heroPosterLqip.js — 24px base64 placeholder the hero inlines
 *
 * Run: npm run build:hero-poster
 */
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { writeFile, stat } from "node:fs/promises";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
const source = join(root, "assets-src", "nnmc-campus-hero-poster-master.jpg");

// 1600 is the master's native width — there is nothing to gain above it.
const WIDTHS = [828, 1280, 1600];

// Quality is deliberately low for a hero image. Everything downstream of this
// is blurred and scrimmed, so artefacts that would be obvious on a gallery
// photo are invisible here.
const FORMATS = [
    { ext: "avif", encode: (p) => p.avif({ quality: 42, effort: 6 }) },
    { ext: "webp", encode: (p) => p.webp({ quality: 62, effort: 6 }) },
    { ext: "jpg", encode: (p) => p.jpeg({ quality: 68, mozjpeg: true, progressive: true }) },
];

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

async function main() {
    const master = sharp(source);
    const { width, height } = await master.metadata();
    console.log(`source: ${width}x${height} (${kb((await stat(source)).size)})\n`);

    for (const targetWidth of WIDTHS) {
        for (const { ext, encode } of FORMATS) {
            const out = join(publicDir, `nnmc-campus-hero-poster-${targetWidth}.${ext}`);
            const pipeline = sharp(source).resize({
                width: targetWidth,
                withoutEnlargement: true,
                fit: "cover",
            });
            const { size } = await encode(pipeline).toFile(out);
            console.log(`${targetWidth.toString().padStart(4)}px ${ext.padEnd(4)} → ${kb(size)}`);
        }
    }

    // The LQIP is inlined as a data URI, so it costs zero requests and covers
    // the window between first paint and the poster arriving.
    const lqip = await sharp(source)
        .resize({ width: 24 })
        .blur(1.2)
        .webp({ quality: 32, alphaQuality: 0 })
        .toBuffer();
    const dataUri = `data:image/webp;base64,${lqip.toString("base64")}`;
    await writeFile(
        join(root, "src", "assets", "heroPosterLqip.js"),
        `// Generated by scripts/generate-hero-poster.mjs — do not edit by hand.\n` +
            `export const heroPosterLqip =\n    "${dataUri}";\n`,
        "utf8",
    );
    console.log(`\nlqip → ${kb(lqip.length)} → src/assets/heroPosterLqip.js`);
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
